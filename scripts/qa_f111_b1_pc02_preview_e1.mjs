import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const preview=fs.readFileSync(new URL('../modulos/qz_b1_pc02_preview.html',import.meta.url),'utf8');
const teacher=fs.readFileSync(new URL('../src/teacher_quiz_review_f111.js',import.meta.url),'utf8');
const campus=fs.readFileSync(new URL('../campus.html',import.meta.url),'utf8');
const begin=preview.indexOf('const sections=['),end=preview.indexOf('const answers=Object.create(null)',begin);
assert(begin>0&&end>begin,'25-question bank available as declarative array');
const sections=vm.runInNewContext(preview.slice(begin,end)+'\nsections',{});
assert.deepEqual(Array.from(sections.map(s=>s.id)),['A','B','C','D','E']);
assert.deepEqual(Array.from(sections.map(s=>s.points)),[4,5,5,5,6]);
assert.equal(sections.reduce((n,s)=>n+s.points,0),25,'Cambridge printed score totals 25');
assert.equal(sections.reduce((n,s)=>n+s.items.length,0),25,'exactly 25 individual answers, including D4a and D4b');
const ids=sections.flatMap(s=>s.items.map(q=>q[0]));
assert.equal(new Set(ids).size,25,'all question IDs unique');
assert(ids.includes('D4a')&&ids.includes('D4b'),'Cambridge printed question 4 has two distinct gaps');
assert(sections[0].locked===true,'track 3 listening answer UI is disabled');
assert(sections[0].help.includes('Track 3 is NOT yet available'),'track 3 not pretended');
assert(preview.includes('NO PUBLICADO')&&preview.includes('No se permite presentar ni entregar'));
assert(preview.includes('No se registra información de estudiantes.'));
assert(!/fetch\s*\(|XMLHttpRequest|qzProgressSubmit|qzProgressSaveDraft|window\.parent\.postMessage|localStorage|sessionStorage/.test(preview),'preview cannot call backend or persist student progress');
assert(!/claves\s*[:=]\s*[{\[]/.test(preview),'no answer key published in preview');
assert(teacher.includes("else if(level==='B1'&&lesson===8)"),'only B1 PC02 shown as editable teacher preview');
assert(teacher.includes("view.dataset.f111QuizPreview='B1-L8-QA-ONLY'"),'QA only marker');
assert(teacher.includes('previewPC02'),'teacher preview opens correct non-live page');
assert(!teacher.includes("qzProgressTeacherSetAvailability',Object.assign({},qzContext,{leccion:8"),'never activate L8 via current PC01 context');
assert(campus.includes('teacher_quiz_review_f111.js?v=F111B1PC02PREVIEW20261023'),'teacher asset cache updated');
console.log('PASS F111 PC02 E1: authentic units 3-4 B1 L8, sections 4+5+5+5+6=25, track 3 gate, 0% official, preview-only, no student writes');
