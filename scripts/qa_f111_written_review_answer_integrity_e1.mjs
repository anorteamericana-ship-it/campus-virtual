// F111: control offline de integridad de revisión escrita. No toca cuentas reales.
import assert from 'node:assert/strict';
import fs from 'node:fs';
const render=fs.readFileSync(new URL('../src/examenes_render.jsx',import.meta.url),'utf8');
const modes=fs.readFileSync(new URL('../src/examenes_modes.jsx',import.meta.url),'utf8');
const begin=render.indexOf('function exNorm(s) {');
const end=render.indexOf('// Recorre todas las preguntas calificables');
assert.ok(begin>=0&&end>begin,'extraer solamente funciones puras de corrección');
const functions=new Function(render.slice(begin,end)+';return {evalQuestion,exKeyText};')();
const {evalQuestion}=functions;
const review={needsReview:false};
assert.equal(evalQuestion(review,{id:'A1',correct:'yes'},'yes').verdict,'ok');
assert.equal(evalQuestion(review,{id:'A1',correct:'yes'},'no').verdict,'bad');
assert.equal(evalQuestion(review,{id:'A1',correct:'yes'},'').verdict,'empty');
const noKey=evalQuestion(review,{id:'B3'},'The student responded');
assert.equal(noKey.verdict,'review','sin clave pero respondida => revisión manual');
assert.equal(noKey.keyMissing,true);
assert.equal(evalQuestion(review,{id:'B3'},'').verdict,'empty','solo ausencia real => sin responder');
assert.equal(evalQuestion(review,{id:'D4',correct:[]},'Answer').verdict,'review');
assert.equal(evalQuestion(review,{id:'E2',correct:null},'Answer').verdict,'review');
assert.ok(render.includes('const ev = evalQuestion(section, q, val);'),'ReviewBar evalúa incluso claves ausentes');
assert.ok(render.includes('Clave no disponible · revisión manual'),'etiqueta inequívoca para docente');
assert.ok(modes.includes('El intento no contiene respuestas guardadas verificables.'),'examen sin payload alerta');
assert.ok(modes.includes('No se pudieron interpretar las respuestas guardadas del intento.'),'JSON ilegible alerta');
assert.ok(modes.includes('storedFields > 0 && responseCount === 0'),'desajuste de banco/ids falla cerrado');
assert.ok(modes.includes('if (answerIntegrityError) {'),'prohibido cerrar con respuestas ilegibles');
assert.ok(modes.includes('disabled={!!busy || !!answerIntegrityError}'),'bloqueo visible botón nota');
assert.ok(modes.includes('examGetAttempt')&&modes.includes('examGetReview'),'revisión lee expediente y su estado del servidor');
console.log('PASS F111 examen escrito: contestada sin clave => revisión; sin respuesta => vacío; payload ilegible/desajuste bloquea nota; cero datos reales');
