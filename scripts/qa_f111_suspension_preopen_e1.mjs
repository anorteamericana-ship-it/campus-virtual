import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../src/vista_docente.jsx', import.meta.url), 'utf8');
const start = source.indexOf('function vdSuspensionKey(');
const end = source.indexOf('// LeccionRow —', start);
assert(start >= 0 && end > start, 'helpers de suspensión accesibles');
const sandbox = vm.createContext({});
vm.runInContext(source.slice(start, end) + '\nthis.policy = {vdSuspensionKey, vdSuspensionEstado, vdSuspensionPermitida};', sandbox);
const { vdSuspensionKey: key, vdSuspensionEstado: status, vdSuspensionPermitida: allowed } = sandbox.policy;
const sample = {cod_grupo:'B1-LM69-0826',nivel:'B1',leccion:3,riel:'curso',fecha:'2026-10-21',estado:'PROGRAMADA'};
let count=0;
function check(label, fn){fn(); count++; console.log('PASS',String(count).padStart(2,'0'),label);}
check('docente autorizado',()=>assert.equal(allowed(sample,'DOCENTE'),true));
check('profesor autorizado',()=>assert.equal(allowed(sample,'PROFESOR'),true));
check('teacher autorizado',()=>assert.equal(allowed(sample,'TEACHER'),true));
check('estudiante denegado',()=>assert.equal(allowed(sample,'ESTUDIANTE'),false));
check('superadmin no suplanta al docente',()=>assert.equal(allowed(sample,'SUPERADMIN'),false));
check('admin no suplanta al docente',()=>assert.equal(allowed(sample,'ADMIN'),false));
check('sin rol denegado',()=>assert.equal(allowed(sample,''),false));
check('sin grupo denegado',()=>assert.equal(allowed({...sample,cod_grupo:''},'DOCENTE'),false));
check('sin nivel denegado',()=>assert.equal(allowed({...sample,nivel:''},'DOCENTE'),false));
check('lección inválida denegada',()=>assert.equal(allowed({...sample,leccion:0},'DOCENTE'),false));
check('fecha inválida denegada',()=>assert.equal(allowed({...sample,fecha:'21/10/2026'},'DOCENTE'),false));
check('cerrada denegada',()=>assert.equal(allowed({...sample,estado:'CERRADA'},'DOCENTE'),false));
check('suspendida denegada',()=>assert.equal(allowed({...sample,estado:'SUSPENDIDA'},'DOCENTE'),false));
check('programada futura autorizada',()=>assert.equal(allowed({...sample,fecha:'2027-01-02'},'DOCENTE'),true));
check('programada pasada admite solicitud excepcional',()=>assert.equal(allowed(sample,'DOCENTE'),true));
check('I CAN admite petición',()=>assert.equal(allowed({...sample,riel:'ican'},'DOCENTE'),true));
check('clave incluye riel',()=>assert.notEqual(key(sample),key({...sample,riel:'ican'})));
check('estado local pendiente',()=>assert.equal(status(sample,{[key(sample)]:'PENDIENTE'}),'PENDIENTE'));
check('estado local aprobado',()=>assert.equal(status(sample,{[key(sample)]:'APROBADA'}),'APROBADA'));
check('estado local rechazado',()=>assert.equal(status(sample,{[key(sample)]:'RECHAZADA'}),'RECHAZADA'));
check('estado del calendario reconocido',()=>assert.equal(status({...sample,solicitud_estado:'APROBADA'},{}),'APROBADA'));
check('estado inválido no mostrado',()=>assert.equal(status({...sample,solicitud_estado:'ERROR'},{}),''));
check('estado local tiene precedencia',()=>assert.equal(status({...sample,solicitud_estado:'RECHAZADA'},{[key(sample)]:'PENDIENTE'}),'PENDIENTE'));
check('acceso sin abrir cierre',()=>assert.match(source,/onSolicitarSuspension=\{abrirSolicitudSinCierre\}/));
check('cuatro secciones de próximas conectadas',()=>assert.equal((source.match(/\.\.\.suspensionProps\(lec\)/g)||[]).length,4));
check('botón independiente y sin guardar asistencia',()=>assert.match(source,/Solicitar suspensión · sin abrir clase/));
check('modal de suspensión fuera de cierre',()=>assert(source.indexOf('{modalSuspLec && (')<source.indexOf('{modalLec && (')));
check('doble clic protegido por ref',()=>assert.match(source,/if \(enviandoRef\.current\) return/));
check('respuesta pendiente visible',()=>assert.match(source,/Solicitud pendiente de aprobación/));
check('diálogo accesible',()=>assert.match(source,/aria-labelledby="vd-suspension-title"/));
check('error accesible',()=>assert.match(source,/role="alert" aria-live="assertive"/));
check('pasado explicado',()=>assert.match(source,/solicitud será excepcional/));
check('sin mutación de notas por acceso directo',()=>assert(!source.slice(source.indexOf('const abrirSolicitudSinCierre'),source.indexOf('const abrirSolicitudSinCierre')+450).includes('postCerrarLeccionCompleta')));
console.log('F111 suspensión preapertura:',count+'/'+count,'PASS (política sintética + contrato UI estático)');
