'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync('modulos/examen_oral.html','utf8');
const match=src.match(/<script>\s*([\s\S]*?)<\/script>/);
assert.ok(match,'panel oral institucional sin script');
const script=match[1];
new vm.Script(script,{filename:'f111_oral_browser.js'});
let checks=0;
function pass(pred,label){assert.ok(pred,label);checks++;}
pass(src.includes('id="btn-draft"'),'guardar borrador digital');
pass(src.includes('id="btn-finalize-saved"'),'único cierre histórico');
pass(src.includes('id="r50-admin-panel" style="display:none"'),'panel R50 oculto');
pass(script.includes("getSesion().rol||'').toLowerCase()==='superadmin'"),'solo superadmin aprueba');
pass(script.includes("const motivo=prompt("),'justificación explícita de cero');
pass(script.includes('motivo.trim().length<25'),'mínimo de justificación');
pass(script.includes('confirmo_cero_incorrecto:true'),'confirmación administrativa positiva');
pass(script.includes("'r50AprobarConciliacionOral'"),'endpoint aprobacion');
pass(script.includes("'r50EstadoConciliacionOral'"),'lectura de estado');
pass(script.includes('cierre_docente_original:true'),'cierre docente original sin solicitud R50');
pass(script.includes("'r50CerrarOralConciliado'"),'cierre autorizado en vez de bypass general');
pass(script.includes('confirmar_nota_oficial:true'),'docente confirma individualmente');
pass(script.includes('function r52CierreDocenteOriginalF111()'),'cierre docente original de grupo acotado');
pass(script.includes('const cierreDocenteOriginal=r52CierreDocenteOriginalF111();'),'ruta especial de docente autor, sin dos aprobaciones');
pass(script.includes('function r50AccionHabilitadaF111(codigo)'),'acciones R50 individuales');
pass(script.includes("['SIN_SOLICITUD','ACTUALIZACION_REQUERIDA','APROBADO'].includes"),'solicitud, renovación y aprobado habilitan solo la ruta con preflight');
pass(script.includes("!state.reviewConflicts?.[String(s.codigo)]||r50AccionHabilitadaF111(s.codigo)"),'aviso visual no bloquea autorización validada');
pass(script.includes("state.reviewConflicts?.[String(state.selected.codigo)]&&!r50EsGrupoF111()"),'no hay bypass general de conflicto');
pass(script.includes('cierre_docente_original:true'),'CORE decide si el cero posterior es elegible, jamás solo el UI');
pass(script.includes('r50_expediente_cambio_revisar'),'expediente modificado conserva bloqueo seguro');
pass(script.includes("st==='ACTUALIZACION_REQUERIDA'"),'superadmin no aprueba solicitud desactualizada');
pass(script.includes("button.textContent='GUARDAR NOTA OFICIAL'"),'docente ve acción oficial directa');
pass(script.includes("if(status==='BORRADOR'&&!r52CierreDocenteOriginalF111())"),'estado R50 no sobreescribe botón de cierre directo');
pass(script.includes('if(r52CierreDocenteOriginalF111())return true'),'cierre directo elegible solo en grupo y rol autorizado');
pass(script.includes('No se crean solicitudes R50 ni se requiere aprobación del superadmin'),'no fuerza revisión administrativa en evaluación original');
pass(script.includes("cierreDocenteOriginal?'r50CerrarOralConciliado'"),'cierre individual por endpoint autenticado');
pass(script.includes("state.r50ApprovedFor=''"),'carga nuevo grupo borra permiso anterior');
pass(script.includes("state.reviewConflicts[String(student.codigo)]=true"),'nota sin autorización permanece protegida');
pass(script.includes("const res=await api('oralGeneratePdf',ident)"),'PDF usa motor existente');
pass(script.includes("const individualDownload=document.getElementById('f111-pdf-download')"),'descarga reutiliza documento');
pass(script.includes('if(individualDownload)individualDownload.click()'),'descarga automática tras confirmar PDF oficial');
pass(script.includes("estado==='BORRADOR'?'Nota oficial confirmada, PDF archivado y descarga iniciada."),'primer cierre descarga solamente al completar nota y PDF');
pass(script.includes('r50RefreshAdminF111();r50RefreshTeacherF111();const cerrado='),'actualiza control en cada ficha');
pass(script.includes("'B1-LM69-C2-0526'"),'solo grupo auditado R50');
pass(script.includes("String(state.panel?.nivel)==='B2'"),'solo nivel B2');
pass(script.includes('Number(state.panel?.leccion)===9'),'solo lección 9');
pass(script.includes("if(state.dirty)return toast('Guardá primero"),'no cierra cambios sin guardar');
pass(script.includes("btn.textContent='GUARDAR BORRADOR'"),'borrador no genera PDF');
pass(!src.includes('id="btn-print-saved" type="button" style="display:block"'),'sin PDF de borrador');
console.log('F111_R50_ORAL_TEACHER_ADMIN_UI_E1_PASS checks='+checks+' writes=0 grades=0 pdfs=0');
